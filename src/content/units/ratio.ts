const V = '0.1.0';

// ---------- ratio.concept ----------
function concept(level: Level, rng: Rng): Exercise {
  const id = 'ratio.concept';
  if (level === 1) {
    const [a, b] = [int(rng, 2, 15), int(rng, 2, 15)];
    const b2 = a === b ? b + 1 : b;
    return {
      subtopicId: id,
      level,
      prompt: `בכיתה יש ${m(a)} בנות ו-${m(b2)} בנים. מה היחס בין מספר הבנות למספר הבנים?`,
      answer: { kind: 'ratio', parts: [a, b2] },
      hints: [
        'משווים בין שתי כמויות: בנות ובנים. השוואה כזו כותבים כיחס, עם נקודתיים באמצע.',
        'הסדר ביחס נקבע לפי השאלה: מה שמוזכר ראשון בשאלה נכתב ראשון ביחס. כאן השאלה מתחילה בבנות.',
        `כתבי קודם את מספר הבנות, אחריו נקודתיים, ואז את מספר הבנים: ${m(a + ':?')}`,
      ],
      solution: [`השאלה: בנות לעומת בנים.`, `בנות: ${m(a)}, בנים: ${m(b2)}.`, `היחס: ${r(a, b2)}`],
      mistakes: [],
    };
  }
  if (level === 2) {
    const [x, y] = coprimeTuple(rng, 2, 2, 7);
    const k = int(rng, 1, 2);
    const orange = x * k;
    const blue = y * k;
    return {
      subtopicId: id,
      level,
      prompt: `בציור יש עיגולים כתומים וכחולים. מה היחס בין מספר העיגולים **הכחולים** למספר העיגולים **הכתומים**?`,
      answer: { kind: 'ratio', parts: [blue, orange] },
      hints: [
        'מבקשים יחס בין שתי קבוצות בציור. כדי לכתוב אותו צריך לדעת כמה יש מכל צבע.',
        'קודם סופרים כל צבע בנפרד. אחר כך בודקים איזה צבע מוזכר ראשון **בשאלה**: הוא נכתב ראשון ביחס, גם אם בציור יש ממנו פחות.',
        'ספרי את העיגולים הכחולים. בשאלה הם ראשונים, אז המספר שלהם בא לפני הנקודתיים.',
      ],
      solution: [`כחולים: ${m(blue)}, כתומים: ${m(orange)}.`, `היחס כחולים:כתומים הוא ${r(blue, orange)}.`],
      mistakes: [],
      visual: {
        type: 'bars',
        groups: [
          { label: 'כתומים', count: orange, color: 'a' },
          { label: 'כחולים', count: blue, color: 'b' },
        ],
      },
    };
  }
  // level 3: scaling a recipe
  const [a, b] = coprimeTuple(rng, 2, 1, 5);
  const k = int(rng, 2, 6);
  const ans = b * k;
  return {
    subtopicId: id,
    level,
    prompt: `במתכון לעוגה שמים ${m(a)} כוסות קמח על כל ${m(b)} כוסות חלב. הכינו עוגה גדולה עם ${m(a * k)} כוסות קמח. כמה כוסות חלב צריך?`,
    answer: { kind: 'number', value: ans, unit: 'כוסות' },
    hints: [
      'מגדילים מתכון: יש יותר קמח מבמתכון המקורי, וצריך למצוא כמה חלב מתאים לכמות החדשה.',
      'ביחס לא מוסיפים, מכפילים. בודקים **פי כמה** גדל הקמח, ומגדילים את החלב פי אותו מספר בדיוק.',
      `פי כמה גדל הקמח? חשבי ${m(`${a * k} ÷ ${a}`)}`,
    ],
    solution: [`הקמח גדל מ-${m(a)} ל-${m(a * k)}, כלומר פי ${m(k)}.`, `גם החלב גדל פי ${m(k)}: ${m(`${b} × ${k} = ${ans}`)}.`],
    mistakes: mistakes(isNum(ans), [
      numMistake(b + (a * k - a), 'הוספת לחלב את אותה כמות שנוספה לקמח. ביחס לא מוסיפים, מכפילים: אם הקמח גדל פי מספר מסוים, גם החלב גדל פי אותו מספר.'),
    ]),
  };
}

// ---------- ratio.part-whole ----------
function partWhole(level: Level, rng: Rng): Exercise {
  const id = 'ratio.part-whole';
  if (level === 1) {
    const [a, b] = [int(rng, 2, 12), int(rng, 2, 12)];
    const total = a + b;
    return {
      subtopicId: id,
      level,
      prompt: `בשקית יש ${m(a)} סוכריות אדומות ו-${m(b)} סוכריות ירוקות. מה היחס בין מספר הסוכריות האדומות למספר **כל** הסוכריות בשקית?`,
      answer: { kind: 'ratio', parts: [a, total] },
      hints: [
        'שואלים על יחס בין חלק (האדומות) לבין **כל** השקית, לא בין האדומות לירוקות.',
        '"כל הסוכריות" זה כל הצבעים ביחד. קודם מוצאים כמה יש בסך הכול, ואז כותבים חלק : שלם.',
        `כמה סוכריות יש בשקית בסך הכול? חשבי ${m(`${a} + ${b}`)}`,
      ],
      solution: [`כל הסוכריות: ${m(`${a} + ${b} = ${total}`)}.`, `אדומות לכל הסוכריות: ${r(a, total)}.`],
      mistakes: [ratioMistake([a, b], `זה יחס של **חלק לחלק** (אדומות לירוקות). השאלה שואלת על **חלק לשלם**: אדומות לכל הסוכריות, כלומר ${m(total)}.`)],
    };
  }
  if (level === 2) {
    const [a, b] = coprimeTuple(rng, 2, 1, 9);
    const total = a + b;
    const g = gcdAll([a, total]);
    return {
      subtopicId: id,
      level,
      prompt: `בחוג היחס בין מספר הבנים למספר הבנות הוא ${r(a, b)}. איזה חלק מכל המשתתפים הם בנים? (כתבי שבר, למשל ${m('3/8')})`,
      answer: { kind: 'number', value: a / total, display: `${a / g}/${total / g}` },
      hints: [
        'שואלים איזה חלק מ**כל** המשתתפים הם בנים. התשובה היא שבר: בנים חלקי כולם.',
        `היחס ${r(a, b)} מתאר "קבוצה קטנה" שחוזרת על עצמה: ${m(a)} בנים ו-${m(b)} בנות. אם מבינים איזה חלק מהקבוצה הקטנה הם בנים, זה אותו חלק מכל החוג.`,
        `כמה ילדים יש בקבוצה הקטנה? ${m(`${a} + ${b}`)}. כמה מהם בנים?`,
      ],
      solution: [`בכל קבוצה: ${m(`${a} + ${b} = ${total}`)} ילדים.`, `מתוכם ${m(a)} בנים, כלומר ${m(`${a}/${total}`)} מהמשתתפים.`],
      mistakes: mistakes(isNum(a / total), [
        numMistake(a / b, `${m(`${a}/${b}`)} זה בנים חלקי **בנות**. השאלה שואלת חלק מ**כל** המשתתפים, אז במכנה צריך את כולם: ${m(total)}.`),
      ]),
    };
  }
  const q = pick(rng, [5, 7, 8, 9, 10, 11, 12]);
  let p = int(rng, 1, q - 1);
  while (gcdAll([p, q]) !== 1) p = int(rng, 1, q - 1);
  const rest = q - p;
  return {
    subtopicId: id,
    level,
    prompt: `${m(`${p}/${q}`)} מהכדורים בארגז הם אדומים, וכל השאר כחולים. מה היחס בין מספר הכדורים האדומים למספר הכדורים הכחולים?`,
    answer: { kind: 'ratio', parts: [p, rest] },
    hints: [
      'שואלים על יחס בין שני חלקים: אדומים לכחולים. השבר בשאלה הוא חלק מכל הארגז (חלק לשלם).',
      `טריק: דמייני ארגז שיש בו בדיוק ${m(q)} כדורים, כמו המכנה. ככה השבר הופך למספרים רגילים שקל לספור.`,
      `בארגז כזה יש ${m(p)} אדומים. כמה נשארים כחולים? ${m(`${q} − ${p}`)}`,
    ],
    solution: [`נניח ${m(q)} כדורים: ${m(p)} אדומים.`, `כחולים: ${m(`${q} − ${p} = ${rest}`)}.`, `אדומים:כחולים = ${r(p, rest)}.`],
    mistakes: [ratioMistake([p, q], `${r(p, q)} זה אדומים ל**כל** הכדורים (חלק לשלם). השאלה שואלת אדומים לכחולים (חלק לחלק).`)],
  };
}

// ---------- ratio.three ----------
function three(level: Level, rng: Rng): Exercise {
  const id = 'ratio.three';
  // Three different counts, so the order in the answer really matters.
  let [a, b, c] = [0, 0, 0];
  do [a, b, c] = [int(rng, 1, 9), int(rng, 1, 9), int(rng, 1, 9)];
  while (a === b || b === c || a === c);
  if (level === 1) {
    return {
      subtopicId: id,
      level,
      prompt: `בסלט יש ${m(a)} עגבניות, ${m(b)} מלפפונים ו-${m(c)} פלפלים. מה היחס עגבניות : מלפפונים : פלפלים?`,
      answer: { kind: 'ratio', parts: [a, b, c] },
      hints: [
        'מבקשים יחס בין שלוש כמויות. כותבים אותו כמו יחס רגיל, רק עם שני נקודתיים.',
        'עוברים על השאלה לפי הסדר שבו ביקשו את היחס, ולכל ירק מחפשים את המספר שלו בתיאור.',
        `עגבניות ראשונות ביחס: ${m(a + ':?:?')}`,
      ],
      solution: [`${r(a, b, c)}`],
      mistakes: [],
    };
  }
  if (level === 2) {
    return {
      subtopicId: id,
      level,
      prompt: `בסלט יש ${m(a)} עגבניות, ${m(b)} מלפפונים ו-${m(c)} פלפלים. מה היחס **פלפלים : עגבניות : מלפפונים**?`,
      answer: { kind: 'ratio', parts: [c, a, b] },
      hints: [
        'מבקשים יחס בין שלושה ירקות, אבל בסדר שונה מהסדר שבו הם מתוארים. זה המלכוד בשאלה.',
        'הסדר ביחס נקבע לפי מה שביקשו, לא לפי התיאור. כתבי קודם את שמות הירקות בסדר המבוקש, ורק אז הציבי את המספרים.',
        `פלפלים ראשונים: ${m(c + ':?:?')}. מי בא אחריהם בשאלה?`,
      ],
      solution: [`פלפלים: ${m(c)}, עגבניות: ${m(a)}, מלפפונים: ${m(b)}.`, `${r(c, a, b)}`],
      mistakes: [ratioMistake([a, b, c], 'זה הסדר שבו הירקות מופיעים בתיאור. בשאלה ביקשו סדר אחר: פלפלים, עגבניות, מלפפונים.')],
    };
  }
  const [x, y, z] = coprimeTuple(rng, 3, 1, 7);
  const k = int(rng, 2, 6);
  const ans = z * k;
  return {
    subtopicId: id,
    level,
    prompt: `בחנות היחס בין חולצות לבנות, שחורות ואדומות הוא ${r(x, y, z)}. בחנות יש ${m(x * k)} חולצות לבנות. כמה חולצות אדומות יש?`,
    answer: { kind: 'number', value: ans, unit: 'חולצות' },
    hints: [
      'שואלים כמה חולצות אדומות יש. יודעים את היחס, ויודעים כמה חולצות לבנות יש באמת.',
      'היחס הוא כמו מתכון. בודקים פי כמה הלבנות במציאות גדולות מהמספר שלהן ביחס, ומגדילים גם את האדומות פי אותו מספר.',
      `פי כמה? חשבי ${m(`${x * k} ÷ ${x}`)}`,
    ],
    solution: [`${m(`${x * k} ÷ ${x} = ${k}`)}: הכמויות גדולות פי ${m(k)} מהיחס.`, `אדומות: ${m(`${z} × ${k} = ${ans}`)}.`],
    mistakes: mistakes(isNum(ans), [
      numMistake(z + (x * k - x), 'הוספת במקום להכפיל. כל החלקים ביחס גדלים פי אותו מספר.'),
      numMistake(y * k, 'זה מספר החולצות השחורות. שימי לב: האדומות הן החלק השלישי ביחס.'),
    ]),
  };
}

